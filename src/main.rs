use shortest_color::shorten_css_color;

fn main() {
    let test_cases = vec![
        // Основные цвета -> keywords (когда keyword короче)
        ("#ff0000", "red"),        // 7 -> 3
        ("#008000", "green"),      // 7 -> 5  
        ("#000080", "navy"),       // 7 -> 4
        ("#800080", "purple"),     // 7 -> 6
        ("#808080", "gray"),       // 7 -> 4
        ("#000000", "#000"),       // 7 -> 4 (короче чем black=5)
        ("#ffffff", "#fff"),       // 7 -> 4 (короче чем white=5)
        
        // Hex сокращения -> короткий hex (когда hex короче keyword)
        ("#ff00ff", "#f0f"),       // 7 -> 4 (короче чем magenta=7)
        ("#00ffff", "#0ff"),       // 7 -> 4 (короче чем cyan=4, равны)
        ("#ffff00", "#ff0"),       // 7 -> 4 (короче чем yellow=6)
        ("#aabbcc", "#abc"),       // 7 -> 4
        ("#112233", "#123"),       // 7 -> 4
        ("#ddeeff", "#def"),       // 7 -> 4
        
        // Цвета которые нельзя сократить
        ("#123456", "#123456"),    // нет паттерна сокращения
        ("#abcdef", "#abcdef"),    // нет паттерна сокращения
        ("#ff5733", "#ff5733"),    // нет паттерна сокращения
        
        // RGB -> shortest возможное
        ("rgb(255, 0, 0)", "red"),           // -> keyword
        ("rgb(170, 187, 204)", "#abc"),      // -> короткий hex
        ("rgb(18, 52, 86)", "#123456"),      // -> полный hex
        ("rgb(0, 255, 255)", "#0ff"),        // -> короткий hex
        
        // RGBA с прозрачностью
        ("rgba(255, 0, 0, 0.5)", "#ff000080"),     // полупрозрачный красный
        ("rgba(170, 187, 204, 0.2)", "#abc3"),     // короткий hex с alpha
        ("rgba(255, 255, 255, 1)", "#fff"),        // полностью непрозрачный -> короткий hex
        
        // HSL -> shortest возможное  
        ("hsl(0, 100%, 50%)", "red"),        // 3 символа - shortest
        ("hsl(120, 100%, 50%)", "#0f0"),     // 4 символа (lime тоже 4, выбираем hex)
        ("hsl(240, 100%, 50%)", "#00f"),     // 4 символа (blue тоже 4, выбираем hex)
        ("hsl(300, 100%, 50%)", "#f0f"),     // 4 символа
        
        // HSLA с прозрачностью
        ("hsla(0, 100%, 50%, 0.5)", "#ff000080"), // полупрозрачный красный
        ("hsla(240, 100%, 50%, 1)", "#00f"),       // короткий hex
        
        // Именованные цвета -> shortest возможное
        ("red", "red"),                      // уже shortest (3 символа)
        ("blue", "#00f"),                    // hex короче (4 vs 4, но приоритет hex)
        ("white", "#fff"),                   // hex короче (4 vs 5)
        ("rebeccapurple", "#639"),           // hex намного короче (4 vs 12)
        
        // Краевые случаи
        ("", ""),                        // пустая строка
        ("invalid", "invalid"),          // невалидный цвет
        ("rgb(300, 0, 0)", "rgb(300, 0, 0)"), // невалидный RGB
        ("#gggggg", "#gggggg"),         // невалидный hex
        ("hsl(400, 200%, 150%)", "hsl(400, 200%, 150%)"), // невалидный HSL
        
        // С пробелами
        ("  #ff0000  ", "red"),
        (" rgb(255, 0, 0) ", "red"),
        ("  white  ", "#fff"),
        
        // Разные регистры
        ("#FF0000", "red"),
        ("RGB(255, 0, 0)", "red"),
        ("WHITE", "#fff"),
        ("Red", "red"),
    ];

    println!("🧪 Тестируем функцию сокращения цветов:\n");
    
    let mut passed = 0;
    let mut failed = 0;
    
    for (input, expected) in test_cases {
        let result = shorten_css_color(input);
        let status = if result == expected { 
            passed += 1;
            "✅" 
        } else { 
            failed += 1;
            "❌" 
        };
        
        println!("{:<25} -> {:<12} {} {}", 
                 format!("\"{}\"", input), 
                 format!("\"{}\"", result),
                 status,
                 if result != expected { format!("(ожидался \"{}\")", expected) } else { "".to_string() }
        );
    }
    
    println!("\n📊 Результаты: {} ✅ прошло, {} ❌ не прошло", passed, failed);
    
    if failed == 0 {
        println!("🎉 Все тесты прошли успешно!");
    }
}